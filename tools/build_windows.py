"""Build the standalone Windows folder: ChipLoom.exe (window) and chiploom-cli.exe (console CLI).

    python -m pip install -e ".[desktop]" pyinstaller
    python tools/build_windows.py [--zip] [--no-icon]

Output (all under the git-ignored build/ folder):
    build/windows/ChipLoom/ChipLoom.exe           tracker window, no console
    build/windows/ChipLoom/chiploom-cli.exe       command line tool for agents
    build/windows/ChipLoom-<version>-windows.zip   with --zip

FFmpeg is deliberately not bundled. The window and `chiploom render` explain that
FFmpeg with libopenmpt on PATH is required for audio; everything else works without it.
When the pinned libxmp from `python tools/setup_reference.py` exists, its DLL is bundled
for real-time playback in the window (libxmp is MIT licensed; its notice is copied too).
The libxmp reference renderer (`--engine xmp`) remains a developer tool and is not frozen.
"""
from pathlib import Path
import argparse
import os
import shutil
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from tracker4agents import __version__  # noqa: E402

DEFAULT_OUTPUT = ROOT / "build" / "windows"
APP_NAME = "ChipLoom"

CLI_ENTRY = '''\
from tracker4agents.cli import main

if __name__ == "__main__":
    raise SystemExit(main())
'''

# A windowed executable has no stdout/stderr: keep argparse and the CLI from crashing,
# and show startup problems in a message box instead of losing them.
GUI_ENTRY = '''\
import io
import sys


def _message(text):
    try:
        import ctypes
        ctypes.windll.user32.MessageBoxW(None, text[-1800:], "ChipLoom", 0x10)
    except Exception:
        pass


if __name__ == "__main__":
    captured = io.StringIO()
    sys.stdout = sys.stdout or captured
    sys.stderr = captured
    try:
        from tracker4agents.cli import main
        code = main(["gui", *sys.argv[1:]])
    except SystemExit as exit_request:
        code = exit_request.code if isinstance(exit_request.code, int) else 1
    except BaseException:
        import traceback
        captured.write(traceback.format_exc())
        code = 1
    if code:
        _message(captured.getvalue() or f"ChipLoom stopped with code {code}.")
    raise SystemExit(code)
'''

SPEC = '''\
# Generated by tools/build_windows.py; do not edit.
from PyInstaller.building.api import COLLECT, EXE, PYZ
from PyInstaller.building.build_main import Analysis

# Qt modules that the window never imports; leaving them out keeps the folder small.
UNUSED_QT = [
    "PySide6." + name for name in (
        "QtWebEngineCore", "QtWebEngineWidgets", "QtWebEngineQuick", "QtWebChannel", "QtWebSockets", "QtPdf", "QtPdfWidgets",
        "QtQml", "QtQuick", "QtQuickWidgets", "QtQuickControls2", "Qt3DCore", "Qt3DRender", "Qt3DInput", "Qt3DLogic",
        "Qt3DAnimation", "Qt3DExtras", "QtCharts", "QtDataVisualization", "QtGraphs", "QtSql", "QtTest", "QtDesigner",
        "QtHelp", "QtOpenGL", "QtOpenGLWidgets", "QtBluetooth", "QtNfc", "QtSensors", "QtSerialPort", "QtSvg",
        "QtSvgWidgets", "QtPositioning", "QtLocation", "QtRemoteObjects", "QtScxml", "QtStateMachine", "QtTextToSpeech",
        "QtSpatialAudio", "QtVirtualKeyboard", "QtShaderTools", "QtUiTools", "QtXml", "QtConcurrent", "QtDBus",
    )
] + ["tkinter", "unittest", "pydoc"]

analysis = Analysis(
    [{gui_entry!r}, {cli_entry!r}],
    pathex=[{root!r}],
    datas=[({assets!r}, "tracker4agents/assets")] + {extra_datas!r},
    binaries={extra_binaries!r},
    hiddenimports=["tracker4agents.desktop", "tracker4agents.desktop_samples", "tracker4agents.desktop_services"],
    excludes=UNUSED_QT,
    noarchive=False,
)
archive = PYZ(analysis.pure)
# analysis.scripts also holds PyInstaller's bootstrap and runtime hooks; every executable needs them.
bootstrap = [item for item in analysis.scripts if item[0].startswith("pyi")]
gui_script = [item for item in analysis.scripts if item[0] == "gui_entry"]
cli_script = [item for item in analysis.scripts if item[0] == "cli_entry"]
assert gui_script and cli_script, analysis.scripts
gui = EXE(archive, bootstrap + gui_script, exclude_binaries=True, name="ChipLoom", console=False, icon={icon!r})
cli = EXE(archive, bootstrap + cli_script, exclude_binaries=True, name="chiploom-cli", console=True, icon={icon!r})
COLLECT(gui, cli, analysis.binaries, analysis.datas, name="ChipLoom", strip=False, upx=False)
'''


def libxmp_files() -> tuple[list, list]:
    """The pinned local libxmp DLL and its license notice, when tools/setup_reference.py has built them."""
    import json
    try:
        manifest = json.loads((ROOT / ".tools" / "libxmp" / "manifest.json").read_text(encoding="utf-8"))
        library = Path(manifest["library"])
    except (OSError, ValueError, KeyError, TypeError):
        return [], []
    if not library.is_file():
        return [], []
    notice = Path(manifest.get("license", ""))
    return [(str(library), ".")], ([(str(notice), "licenses/libxmp")] if notice.is_file() else [])


def write_icon(path: Path) -> bool:
    """Write a multi-size PNG-compressed .ico from the bundled logo, using Qt only."""
    os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
    try:
        from PySide6.QtCore import QBuffer, QByteArray, QIODevice, Qt
        from PySide6.QtGui import QGuiApplication, QImage, QPainter
    except ImportError:
        return False
    app = QGuiApplication.instance() or QGuiApplication([])  # noqa: F841 - keeps Qt initialised
    logo = QImage(str(ROOT / "tracker4agents" / "assets" / "chiploom-logo.png"))
    if logo.isNull():
        return False
    # Same display crop of the approved artwork as the window icon (desktop.brand_icon).
    emblem = logo.copy(100, 160, 520, 410)
    images = []
    for size in (16, 24, 32, 48, 64, 128, 256):
        canvas = QImage(size, size, QImage.Format.Format_ARGB32)
        canvas.fill(Qt.GlobalColor.transparent)
        scaled = emblem.scaled(size, size, Qt.AspectRatioMode.KeepAspectRatio, Qt.TransformationMode.SmoothTransformation)
        painter = QPainter(canvas)
        painter.drawImage((size - scaled.width()) // 2, (size - scaled.height()) // 2, scaled)
        painter.end()
        data, buffer = QByteArray(), QBuffer()
        buffer.setBuffer(data)
        buffer.open(QIODevice.OpenModeFlag.WriteOnly)
        canvas.save(buffer, "PNG")
        images.append((size, bytes(data)))
    header = (0).to_bytes(2, "little") + (1).to_bytes(2, "little") + len(images).to_bytes(2, "little")
    offset, directory, payload = 6 + 16 * len(images), b"", b""
    for size, data in images:
        directory += bytes([size % 256, size % 256, 0, 0]) + (1).to_bytes(2, "little") + (32).to_bytes(2, "little")
        directory += len(data).to_bytes(4, "little") + (offset + len(payload)).to_bytes(4, "little")
        payload += data
    path.write_bytes(header + directory + payload)
    return True


def build(output: Path, icon: bool) -> Path:
    try:
        import PyInstaller.__main__ as pyinstaller
    except ImportError:
        raise SystemExit("PyInstaller is required: python -m pip install pyinstaller") from None
    try:
        import PySide6  # noqa: F401
    except ImportError:
        raise SystemExit('PySide6 is required: python -m pip install -e ".[desktop]"') from None
    build_root = output.resolve()
    if ROOT not in build_root.parents:
        raise SystemExit("The build folder must be inside the repository (build/windows by default).")
    work = build_root / "work"
    shutil.rmtree(work, ignore_errors=True)
    shutil.rmtree(build_root / APP_NAME, ignore_errors=True)
    work.mkdir(parents=True)
    (work / "gui_entry.py").write_text(GUI_ENTRY, encoding="utf-8")
    (work / "cli_entry.py").write_text(CLI_ENTRY, encoding="utf-8")
    icon_path = work / "chiploom.ico"
    has_icon = icon and write_icon(icon_path)
    if icon and not has_icon:
        print("warning: icon not generated; continuing without one", file=sys.stderr)
    extra_binaries, extra_datas = libxmp_files()
    if not extra_binaries:
        print("warning: libxmp not found; the window will fall back to rendered playback "
              "(run python tools/setup_reference.py first for real-time playback)", file=sys.stderr)
    spec = work / "chiploom.spec"
    spec.write_text(SPEC.format(
        gui_entry=str(work / "gui_entry.py"), cli_entry=str(work / "cli_entry.py"), root=str(ROOT),
        assets=str(ROOT / "tracker4agents" / "assets"), icon=str(icon_path) if has_icon else None,
        extra_binaries=extra_binaries, extra_datas=extra_datas,
    ), encoding="utf-8")
    pyinstaller.run([str(spec), "--noconfirm", "--clean", "--distpath", str(build_root), "--workpath", str(work / "pyinstaller")])
    folder = build_root / APP_NAME
    for name in ("ChipLoom.exe", "chiploom-cli.exe"):
        if not (folder / name).is_file():
            raise SystemExit(f"Build failed: {folder / name} is missing.")
    return folder


def make_zip(folder: Path) -> Path:
    archive = folder.parent / f"{APP_NAME}-{__version__}-windows.zip"
    notes = (f"ChipLoom {__version__} for Windows\n\nChipLoom.exe  tracker window\nchiploom-cli.exe  command line tool\n\n"
             "Audio playback and rendering need FFmpeg with libopenmpt on PATH. It is not bundled.\n")
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as target:
        for path in sorted(folder.rglob("*")):
            if path.is_file():
                target.write(path, Path(APP_NAME) / path.relative_to(folder))
        target.writestr(f"{APP_NAME}/README.txt", notes)
    return archive


def main() -> int:
    parser = argparse.ArgumentParser(description="Build the standalone Windows folder with PyInstaller.")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT, help="Build folder inside the repository (default build/windows).")
    parser.add_argument("--zip", action="store_true", help="Also write ChipLoom-<version>-windows.zip next to the folder.")
    parser.add_argument("--no-icon", action="store_true", help="Skip the generated application icon.")
    args = parser.parse_args()
    if sys.platform != "win32":
        raise SystemExit("This build targets Windows.")
    folder = build(args.output, not args.no_icon)
    print(f"Built {folder}")
    if args.zip:
        print(f"Wrote {make_zip(folder)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
