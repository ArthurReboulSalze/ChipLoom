"""Keep the tool table in docs/MCP.md identical to the adapter's TOOLS list.

    python tools/mcp_docs.py            # print the table
    python tools/mcp_docs.py --write    # rewrite the table between the markers in docs/MCP.md
    python tools/mcp_docs.py --check    # exit 1 when docs/MCP.md is out of date (also run by the tests)
"""
from __future__ import annotations

import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "MCP.md"
START, END = "<!-- tools:start (generated by tools/mcp_docs.py) -->", "<!-- tools:end -->"


def tools_table() -> str:
    sys.path.insert(0, str(ROOT))
    from tracker4agents.mcp_server import TOOLS

    def names(values) -> str:
        return ", ".join(f"`{value}`" for value in values) or "-"

    rows = ["| Tool | Read-only | Required arguments | Optional arguments | Purpose |", "| --- | --- | --- | --- | --- |"]
    for tool in TOOLS:
        schema = tool["inputSchema"]
        required = schema.get("required", [])
        optional = [key for key in schema["properties"] if key not in required]
        read_only = "yes" if tool["annotations"]["readOnlyHint"] else "no"
        rows.append(f"| `{tool['name']}` | {read_only} | {names(required)} | {names(optional)} | {tool['description']} |")
    return f"There are {len(TOOLS)} tools.\n\n" + "\n".join(rows)


def current_block(text: str) -> str:
    start, end = text.index(START) + len(START), text.index(END)
    return text[start:end].strip()


def is_current() -> bool:
    return current_block(DOC.read_text(encoding="utf-8")) == tools_table()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    table = tools_table()
    if arguments.write:
        text = DOC.read_text(encoding="utf-8")
        start, end = text.index(START) + len(START), text.index(END)
        DOC.write_text(f"{text[:start]}\n{table}\n{text[end:]}", encoding="utf-8", newline="\n")
        print(f"Updated {DOC.relative_to(ROOT)}.")
    elif arguments.check:
        if not is_current():
            print("docs/MCP.md is out of date; run: python tools/mcp_docs.py --write")
            return 1
        print("docs/MCP.md matches the tools.")
    else:
        print(table)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
